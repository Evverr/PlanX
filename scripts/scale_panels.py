"""
Writes the smaller-panels sizes of the popups and secondary panels into src/styles.css.

Every rule about them gets a copy under :root[data-compact] with its pixel sizes scaled by --k and
rounded to whole pixels (widths and heights to even ones, so what's centred in them stays centred).
Positions on the screen (with env()) and the main bars, done by hand in the styles, are left out.
Run it again after changing those styles: it replaces the block between its markers.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

CSS = Path(__file__).resolve().parent.parent / 'src' / 'styles.css'
BEGIN = '/* Smaller popups and secondary panels: generated by scripts/scale_panels.py, do not edit. */'
END = '/* End of the generated smaller popups. */'

# Rules about these are scaled...
TARGETS = {
    'board-menu', 'menu-icon', 'menu-item', 'menu-line', 'menu-more', 'menu-row', 'menu-switch', 'size-dots', 'size-dot',
    'btn', 'pop', 'confirm', 'help', 'namepop', 'toast', 'recorder', 'recorder-head', 'rec-btn', 'rec-clock', 'rec-close',
    'rec-meter', 'rec-mic', 'rec-preview', 'rec-stop', 'icon-pick', 'icon-grid', 'emoji-grid', 'sticky-grid', 'pick-tabs',
    'pick-emoji', 'pick-glyph', 'color-picker', 'cp-code', 'cp-hue', 'cp-row', 'cp-square', 'cp-swatch', 'cp-wrap',
    'op-pop', 'op-wrap', 'palette-pop', 'paint-fill', 'paint-stroke', 'paint-target', 'tfmt', 'tf-drop', 'tf-item',
    'tf-menu', 'tf-row', 'fpick', 'fsep', 'fb', 'sw', 'sw-btn', 'sw-group', 'swatch', 'draw-panel', 'ink-colors',
    'ink-preset', 'ink-size', 'ink-sizes', 'ink-style', 'table-count', 'more', 'minimap',
}
# ...unless they're about these: done by hand, or not panels at all.
SKIP = {'board-canvas', 'text-edit', 'pick-ghost', 'tip', 'peek', 'peek-overlay', 'peek-head', 'peek-title', 'mm-item',
        'mm-frame', 'mm-view', 'tools', 'tools-more', 'topbar', 'zoom', 'panel', 'more-pop', 'avatar', 'avatars'}
# Properties whose pixels aren't sizes to scale.
KEEP = ('transform', 'box-shadow', 'filter', 'backdrop-filter', '-webkit-backdrop-filter', 'transition', 'animation',
        'mask', '-webkit-mask', 'background', 'background-position', 'background-size', 'outline-offset')
EVEN = ('width', 'height', 'min-width', 'min-height', 'max-width', 'max-height')


def rules(css: str):
    """Top-level rules as (selector, body), outside @-blocks."""
    i, depth, start, out = 0, 0, 0, []
    while i < len(css):
        if css.startswith('/*', i):
            i = css.index('*/', i) + 2
            if depth == 0:
                start = i
            continue
        c = css[i]
        if c == '{':
            if depth == 0:
                sel, body_start = css[start:i].strip(), i + 1
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                if not sel.startswith('@'):
                    out.append((sel, css[body_start:i]))
                start = i + 1
        i += 1
    return out


def parts_of(sel: str) -> list[str]:
    """A selector list's parts, split at its own commas (not those inside :not() or :is())."""
    out, depth, cur = [], 0, ''
    for c in sel:
        depth += (c == '(') - (c == ')')
        if c == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    return [*out, cur]


def scaled(prop: str, value: str) -> str | None:
    if 'env(' in value or prop.startswith(KEEP) and not prop.startswith('background-color'):
        return None
    step = '2px' if prop in EVEN else '1px'

    def one(m: re.Match) -> str:
        n = float(m.group(1))
        if abs(n) <= 1:
            return m.group(0)
        return f'round(calc({m.group(1)}px * var(--k)), {step})'

    out = re.sub(r'(-?\d*\.?\d+)px', one, value)
    return out if out != value else None


def main() -> None:
    css = CSS.read_text()
    if BEGIN in css:
        css = css[:css.index(BEGIN)] + css[css.index(END) + len(END):].lstrip('\n')
    manual = css.index('/* Smaller panels (the board menu')
    made = []
    for sel, body in rules(css[:manual]):
        # Each part of a selector list on its own: those about a popup, not about what's left out.
        keep = []
        for p in parts_of(sel):
            classes = set(re.findall(r'\.([a-zA-Z][\w-]*)', p))
            if classes & TARGETS and not classes & SKIP:
                keep.append(' '.join(p.split()))
        if not keep:
            continue
        decls = []
        for d in body.split(';'):
            if ':' not in d:
                continue
            prop, value = (x.strip() for x in d.split(':', 1))
            v = scaled(prop, value)
            if v:
                decls.append(f'{prop}: {v}')
        if not decls:
            continue
        parts = []
        for p in keep:
            parts.append(p.replace(':root', ':root[data-compact]', 1) if p.startswith(':root') else f':root[data-compact] {p}')
        made.append(f"{', '.join(parts)} {{ {'; '.join(decls)}; }}")
    block = '\n'.join([BEGIN, *made, END]) + '\n\n'
    css = css[:manual] + block + css[manual:]
    CSS.write_text(css)
    print(f'{len(made)} rules', file=sys.stderr)


if __name__ == '__main__':
    main()
